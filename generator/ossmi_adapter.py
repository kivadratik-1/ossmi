#!/usr/bin/env python3
"""Generate an OSSMI male/studded adapter plate as an OpenSCAD model.

Usage:
    python ossmi_adapter.py 8 5
    python ossmi_adapter.py 8 5 -o my_adapter.scad

    to convert scad to stl
    openscad -o ossmi_adapter_8x5.stl ossmi_adapter_8x5.scad
Dimensions in millimeters. No third-party Python packages required.
"""

import argparse
from pathlib import Path

PITCH = 8.0
EDGE_REDUCTION = 0.3
BASE_THICKNESS = 0.8
STUD_DIAMETER = 4.8
STUD_HEIGHT = 1.8


def generate(nx: int, ny: int) -> str:
    width = nx * PITCH - EDGE_REDUCTION
    length = ny * PITCH - EDGE_REDUCTION
    inset = (PITCH - EDGE_REDUCTION) / 2
    return f'''// OSSMI studded adapter plate — generated by ossmi_adapter.py
// Grid: {nx} x {ny} studs
// Overall dimensions: {width:g} x {length:g} x {BASE_THICKNESS + STUD_HEIGHT:g} mm
// Base thickness: {BASE_THICKNESS:g} mm
// Stud diameter / height: {STUD_DIAMETER:g} / {STUD_HEIGHT:g} mm
// Experimental geometry: test physical fit before relying on retention.

$fn = 64;

pitch = {PITCH:g};
edge_reduction = {EDGE_REDUCTION:g};
nx = {nx};
ny = {ny};
base_thickness = {BASE_THICKNESS:g};
stud_diameter = {STUD_DIAMETER:g};
stud_height = {STUD_HEIGHT:g};

plate_width = nx * pitch - edge_reduction;
plate_length = ny * pitch - edge_reduction;
stud_inset = (pitch - edge_reduction) / 2;

union() {{
    // Rectangular base, lower face at Z=0.
    cube([plate_width, plate_length, base_thickness]);

    // Solid studs, facing outward from the top face.
    for (ix = [0 : nx - 1])
        for (iy = [0 : ny - 1])
            translate([stud_inset + ix * pitch,
                       stud_inset + iy * pitch,
                       base_thickness])
                cylinder(h = stud_height, d = stud_diameter);
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate a simple OSSMI studded adapter plate (.scad)")
    parser.add_argument("nx", type=int, help="Number of studs along X")
    parser.add_argument("ny", type=int, help="Number of studs along Y")
    parser.add_argument("-o", "--output", type=Path, help="Output .scad filename")
    args = parser.parse_args()
    if args.nx < 1 or args.ny < 1:
        parser.error("nx and ny must be positive integers")
    if args.nx > 1000 or args.ny > 1000:
        parser.error("nx and ny must not exceed 1000")
    output = args.output or Path(f"ossmi_adapter_{args.nx}x{args.ny}.scad")
    output.write_text(generate(args.nx, args.ny), encoding="utf-8")
    width = args.nx * PITCH - EDGE_REDUCTION
    length = args.ny * PITCH - EDGE_REDUCTION
    print(f"Created {output}: {width:g} x {length:g} x {BASE_THICKNESS + STUD_HEIGHT:g} mm ({args.nx * args.ny} studs)")


if __name__ == "__main__":
    main()
