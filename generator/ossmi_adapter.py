#!/usr/bin/env python3
"""Generate an OSSMI male/studded adapter plate as an OpenSCAD model.

Usage:
    python ossmi_adapter.py 8 5
    python ossmi_adapter.py 8 5 --base 0.8 --stud-d 4.8 --stud-id 3.3 --stud-h 1.8 --edge 0.2 -o my_adapter.scad

    to convert scad to stl
    openscad -o ossmi_adapter_8x5.stl ossmi_adapter_8x5.scad
Dimensions in millimeters. No third-party Python packages required.
"""

import argparse
from pathlib import Path

PITCH = 8.0
EDGE_REDUCTION = 0.2
BASE_THICKNESS = 0.8
STUD_OUTER_DIAMETER = 4.8
STUD_INNER_DIAMETER = 3.3
STUD_HEIGHT = 1.8
THROUGH_BASE = True


def validate_parameters(
    *,
    pitch: float,
    base_thickness: float,
    stud_outer_diameter: float,
    stud_inner_diameter: float,
    stud_height: float,
    edge_reduction: float,
) -> None:
    if min(base_thickness, stud_outer_diameter, stud_inner_diameter, stud_height) <= 0:
        raise ValueError("base_thickness, stud_outer_diameter, stud_inner_diameter, and stud_height must be > 0")
    if edge_reduction < 0:
        raise ValueError("edge_reduction cannot be negative")
    if stud_inner_diameter >= stud_outer_diameter:
        raise ValueError("stud_inner_diameter must be smaller than stud_outer_diameter")
    if stud_outer_diameter > pitch - edge_reduction:
        raise ValueError("stud_outer_diameter is too large: it exceeds the plate edge")


def generate(
    nx: int,
    ny: int,
    *,
    pitch: float = PITCH,
    base_thickness: float = BASE_THICKNESS,
    stud_outer_diameter: float = STUD_OUTER_DIAMETER,
    stud_inner_diameter: float = STUD_INNER_DIAMETER,
    stud_height: float = STUD_HEIGHT,
    edge_reduction: float = EDGE_REDUCTION,
    through_base: bool = THROUGH_BASE,
) -> str:
    validate_parameters(
        pitch=pitch,
        base_thickness=base_thickness,
        stud_outer_diameter=stud_outer_diameter,
        stud_inner_diameter=stud_inner_diameter,
        stud_height=stud_height,
        edge_reduction=edge_reduction,
    )

    width = nx * pitch - edge_reduction
    length = ny * pitch - edge_reduction
    inset = (pitch - edge_reduction) / 2
    total_h = base_thickness + stud_height

    return f'''// OSSMI studded adapter plate — generated by ossmi_adapter.py
// Grid: {nx} x {ny} studs
// Overall dimensions: {width:g} x {length:g} x {total_h:g} mm
// Base thickness: {base_thickness:g} mm
// Stud outer diameter / inner diameter / height: {stud_outer_diameter:g} / {stud_inner_diameter:g} / {stud_height:g} mm
// Edge reduction: {edge_reduction:g} mm
// Through base: {str(through_base).lower()}

$fn = 64;

pitch = {pitch:g};
edge_reduction = {edge_reduction:g};
nx = {nx};
ny = {ny};
base_thickness = {base_thickness:g};
stud_outer_diameter = {stud_outer_diameter:g};
stud_inner_diameter = {stud_inner_diameter:g};
stud_height = {stud_height:g};
through_base = {str(through_base).lower()};

plate_width = nx * pitch - edge_reduction;
plate_length = ny * pitch - edge_reduction;
stud_inset = (pitch - edge_reduction) / 2;
base_height = base_thickness;
stud_height_total = stud_height;

module stud() {{
    difference() {{
        cylinder(h = stud_height_total, d = stud_outer_diameter);
        translate([0, 0, -0.01])
            cylinder(h = stud_height_total + 0.02, d = stud_inner_diameter);
    }}
}}

difference() {{
    union() {{
        // Rectangular base, lower face at Z=0.
        cube([plate_width, plate_length, base_height]);

        // Tubular studs placed on the top face.
        for (ix = [0 : nx - 1])
            for (iy = [0 : ny - 1])
                translate([stud_inset + ix * pitch,
                           stud_inset + iy * pitch,
                           base_height])
                    stud();
    }}

    if (through_base) {{
        for (ix = [0 : nx - 1])
            for (iy = [0 : ny - 1])
                translate([stud_inset + ix * pitch,
                           stud_inset + iy * pitch,
                           base_height - 0.01])
                    cylinder(h = base_height + 0.02, d = stud_inner_diameter);
    }}
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate an OSSMI studded adapter plate (.scad)")
    parser.add_argument("nx", type=int, help="Number of studs along X")
    parser.add_argument("ny", type=int, help="Number of studs along Y")
    parser.add_argument("-o", "--output", type=Path, help="Output .scad filename")
    parser.add_argument("--pitch", type=float, default=PITCH, help="Pitch between stud centers in mm")
    parser.add_argument("--edge", type=float, default=EDGE_REDUCTION, help="Edge reduction in mm")
    parser.add_argument("--base", type=float, default=BASE_THICKNESS, help="Base thickness in mm")
    parser.add_argument("--stud-d", type=float, default=STUD_OUTER_DIAMETER, help="Stud outer diameter in mm")
    parser.add_argument("--stud-id", type=float, default=STUD_INNER_DIAMETER, help="Stud inner diameter in mm")
    parser.add_argument("--stud-h", type=float, default=STUD_HEIGHT, help="Stud height in mm")
    parser.add_argument("--through", dest="through_base", action=argparse.BooleanOptionalAction, default=THROUGH_BASE,
                        help="Create a through hole only through the base thickness")

    args = parser.parse_args()
    if args.nx < 1 or args.ny < 1:
        parser.error("nx and ny must be positive integers")
    if args.nx > 1000 or args.ny > 1000:
        parser.error("nx and ny must not exceed 1000")
    output = args.output or Path(f"ossmi_adapter_{args.nx}x{args.ny}.scad")

    try:
        scad = generate(
            args.nx,
            args.ny,
            pitch=args.pitch,
            base_thickness=args.base,
            stud_outer_diameter=args.stud_d,
            stud_inner_diameter=args.stud_id,
            stud_height=args.stud_h,
            edge_reduction=args.edge,
            through_base=args.through_base,
        )
    except ValueError as exc:
        parser.error(str(exc))

    output.write_text(scad, encoding="utf-8")
    width = args.nx * args.pitch - args.edge
    length = args.ny * args.pitch - args.edge
    total_h = args.base + args.stud_h
    print(f"Created {output}: {width:g} x {length:g} x {total_h:g} mm ({args.nx * args.ny} studs)")


if __name__ == "__main__":
    main()
